def ci(m, lo, hi, f="{:.2f}"):
    return f"{f.format(m)} [{f.format(lo)}, {f.format(hi)}]"


def best(ds, sp, cut):
    g = S[(S.dataset == ds) & (S.split == sp) & (S.cutoff_h.round(2) == round(cut, 2))]
    st = g[g.model.isin(STAT)]
    return st.loc[st.qscore.idxmin()], g[g.model.isin(NAMES)]


