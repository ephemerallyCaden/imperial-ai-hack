"""Write docs/results.md (tables for the README / Devpost) from eval/results/scorecard.csv and flags.csv.

Run after: python eval/forecast_baselines.py && python eval/score_forecasts.py eval/forecasts && python eval/flags.py
"""
import os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
S = pd.read_csv(f"{HERE}/results/scorecard.csv")
F = pd.read_csv(f"{HERE}/results/flags.csv")
OUT = os.path.join(HERE, "..", "docs", "results.md")
NAMES = {"edge_speed": "edge speed", "linear": "linear", "logistic": "logistic", "gompertz": "Gompertz",
         "lvcf": "typical-wound curve"}
MAIN_CUT = {"whad": 4.0, "whimbc": 6.0, "embryo": 0.22, "zaritsky": 2.51}  # ~20% of the series / of median t90
SPLITS = [("whad", "loo_all", "WHAD MCF10A", "unseen wounds (28 wounds, 56 series)"),
          ("whad", "loo_manual", "WHAD MCF10A", "unseen wounds, manual masks only (9)"),
          ("whad", "CC_to_C61", "WHAD MCF10A", "held-out condition: CC to C61"),
          ("whimbc", "loo", "WHiM-BC MCF-7", "unseen wells (24)"),
          ("whimbc", "Monolayer_to_Sphere", "WHiM-BC MCF-7", "held-out condition: ordinary to stem-cell"),
          ("embryo", "loo", "Fly embryo (secondary)", "unseen wounds (62)"),
          ("zaritsky", "loo", "Zaritsky DA3/MDCK (secondary)", "unseen wells (19)")]


def ci(m, lo, hi, f="{:.2f}"):
    return f"{f.format(m)} [{f.format(lo)}, {f.format(hi)}]"


def best(ds, sp, cut):
    g = S[(S.dataset == ds) & (S.split == sp) & (S.cutoff_h.round(2) == round(cut, 2))]
    return g.loc[g.qscore.idxmin()], g


lines = ["# Stitch: results", "",
         "Generated by `eval/results_table.py` from `eval/results/scorecard.csv` (every number, every model, every cut-off) "
         "and `eval/results/flags.csv`. All bands and ranges are leave-one-wound-out conformal: a wound's own outcome never "
         "calibrates its own forecast. CIs: 95%, bootstrap over physical wounds.", "",
         "## Data", "",
         "| Dataset | Cells | Wounds | Frames | Masks | Role |", "|---|---|---|---|---|---|",
         "| WHAD (Zenodo 12806149, CC BY 4.0) | MCF10A, control (CC) vs CYR61 knockdown (C61) | 31 physical wounds (9 manual masks + 22 auto-segmented); 28 pass QC, 56 series | hourly, 20 per part | authors' + our segmenter | **main benchmark** |",
         "| WHiM-BC (Zenodo 8131123, CC BY 4.0) | MCF-7 ordinary (monolayer) vs cancer-stem-cell-enriched (sphere) | 24 wells | 0-27 h, 6-7 per well | authors' | held-out condition |",
         "| Fly embryo (Zenodo 7660424, CC BY 4.0) | Drosophila epidermis, laser wounds | 62 | 1 per min | authors' | secondary |",
         "| Zaritsky 2015 (GigaDB 100118, CC0) | DA3, MDCK, +/- HGF, Met inhibitor | 19 wells | 14.5 min | authors' (noisy) | secondary |",
         "", "WHAD part II is the same wounds as part I filmed later (same position ids, mask IoU 0.82-0.90), so splits are by physical wound (design.md R15). "
         "Segmenter vs WHAD manual masks: IoU 0.84 (part I) / 0.60 (part II), wound-area error 2.1 / 1.5 points of the field.", "",
         "## Headline: unseen WHAD wounds, forecast from the first 4 h of a 19 h series", "",
         "| Forecaster | Quantile score (CRPS approx., lower better) | 90% band coverage | Band width | Median abs. error | Brier P(90% closed by 19 h) |",
         "|---|---|---|---|---|---|"]
_, g = best("whad", "loo_all", 4.0)
for _, r in g.sort_values("qscore").iterrows():
    lines.append(f"| {NAMES[r.model]} | {ci(r.qscore, r.qscore_lo, r.qscore_hi, '{:.4f}')} | {ci(r.coverage, r.cov_lo, r.cov_hi)} | "
                 f"{r.width:.2f} | {r.mae:.3f} | {r.brier:.3f} |")
lines += ["", "Area is relative to the first frame (1 = as wounded). Target coverage is 0.90. "
          "**Typical-wound curve** = 'no change' plus the conformal step: adding other wounds' errors moves its median onto "
          "the typical closure curve, so it is a population-average forecast that ignores this wound's own rate.", "",
          "## Calibration everywhere (best forecaster per row, ~20% of history seen)", "",
          "| Dataset | Test | Cut-off | Best forecaster | 90% band coverage | Quantile score | t50 in range (n) | t90 in range (n) |",
          "|---|---|---|---|---|---|---|---|"]
for ds, sp, dname, test in SPLITS:
    r, _ = best(ds, sp, MAIN_CUT[ds])
    mark = "" if r.cov_lo <= 0.90 <= r.cov_hi or r.coverage >= 0.85 else " **(fails)**"
    lines.append(f"| {dname} | {test} | {r.cutoff_h:g} h | {NAMES[r.model]} | {ci(r.coverage, r.cov_lo, r.cov_hi)}{mark} | {r.qscore:.4f} | "
                 f"{r.t50_in:.2f} ({int(r.t50_n)}) | {r.t90_in:.2f} ({int(r.t90_n)}) |")
f = F[F.cut_h.round(1) == 4.0]
lines += ["", "## Flags (WHAD, unseen wounds, 4 h; thresholds tuned leave-one-wound-out)", "",
          "| Flag | Shipped | Precision | Recall | AUC | Note |", "|---|---|---|---|---|---|"]
notes = {"stall": ("yes", "area at 19 h still >= 90% of the area at the cut-off"),
         "out_of_band": ("as an observation only", "does not predict a forecast going off-track"),
         "measure_again": ("no", "no signal beats chance clearly; open test for the NCA ensemble spread")}
for _, r in f.iterrows():
    sh, note = notes[r.flag]
    a = "" if pd.isna(r.auc) else f"{r.auc:.2f}"
    lines.append(f"| {r.flag.replace('_', ' ')} | {sh} | {r.precision:.2f} | {r.recall:.2f} | {a} | {note} |")
st = F[F.flag == "stall"]
lines += ["", f"Stall across cut-offs: AUC {st.auc.min():.2f}-{st.auc.max():.2f}, precision {st.precision.min():.2f}-{st.precision.max():.2f}, "
          f"recall {st.recall.min():.2f}-{st.recall.max():.2f}.", "",
          "## What does not work (said plainly)", "",
          "- **Calibration does not transfer to a faster-closing cell type.** Bands calibrated on ordinary MCF-7 wells cover only 15-58% of the stem-cell wells' future (target 90%); 97% of their observations fall below the forecast median.",
          "- **Held-out condition on WHAD is tighter than nominal early on**: CC to C61 coverage is lowest at the earliest cut-off and recovers with more history.",
          f"- **No 'measure again' signal**: band width, history-fit error and stall ambiguity give AUC {F[F.flag == 'measure_again'].auc.min():.2f}-{F[F.flag == 'measure_again'].auc.max():.2f} for predicting a bad forecast, inconsistent across cut-offs.",
          "- **Simple models are strong**: a 2-parameter constant-edge-speed model is the best forecaster on WHAD; more history helps every model.",
          "- **On homogeneous sets the typical-wound curve wins early**: on WHiM-BC, fly embryo and Zaritsky, the population-average curve beats extrapolating the wound's own rate at ~20% of history. Per-wound rates only pay off where wounds differ a lot (WHAD).",
          "- **Small numbers**: 28 WHAD wounds (9 with manual masks); coverage CIs are about +/-0.05 to +/-0.15.",
          "- **Time-to-90% is often censored**: most WHAD series do not reach 90% closure within 19 h, so t90 medians are often open-ended.", "",
          "## NCA vs baselines (gate, design.md 5.3)", "",
          "_Pending: scored at the 00:00 gate with `python eval/score_forecasts.py eval/forecasts --gate nca_ensemble`._", "",
          "## Figures", "",
          "`eval/figures/calibration.png`, `error_vs_history.png`, `reliability.png`, `worst_wounds.png` (regenerate with `python eval/figures.py`)."]
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote", os.path.relpath(OUT))
